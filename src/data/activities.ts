export function getActivity(id: string): Activity | undefined {
  return ACTIVITIES.find((a) => a.id === id)
}

export function activitiesByCategory(category: CategoryId): Activity[] {
  return ACTIVITIES.filter((a) => a.category === category)
}

export function activitiesFor(ageGroup: '5-7' | '8-10', learningLanguage: string): Activity[] {
  return ACTIVITIES.filter(
    (a) => a.ageGroups.includes(ageGroup) && a.learningLanguages.includes(learningLanguage as never),
  )
}
